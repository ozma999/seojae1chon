/** 격자 → SVG path(가로로 이어진 칸은 한 사각형으로) */
export function gridPath(grid: string) {
  const rows = grid.replace(/^\n/, '').split('\n');
  let d = '';
  rows.forEach((r, y) => {
    let x = 0;
    while (x < r.length) {
      if (r[x] !== '#') { x++; continue; }
      let e = x;
      while (r[e] === '#') e++;
      d += `M${x} ${y}h${e - x}v1h-${e - x}z`;
      x = e;
    }
  });
  return d;
}
